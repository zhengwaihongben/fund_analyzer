"""Stage E, batch E-4: retention audit of the backtest tables (read-only).

Checks that a stored run is self-consistent, that child rows never point at a
missing run, and that re-submitting the same specification never rewrites or
duplicates the stored result.  It deliberately does **not** delete or prune
anything: choosing a retention period needs the lead's approval.

Run with::

    python scripts/audit_backtest_retention.py [--db PATH] [--report PATH]
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = ROOT / "data" / "database" / "fund_analyzer.db"
REPORT = ROOT / "docs" / "development" / "stageE_retention_audit.md"

CHILDREN = (
    "strategy_backtest_metrics",
    "strategy_backtest_trades",
    "strategy_backtest_equity",
)


def connect(path: Path) -> sqlite3.Connection:
    if not path.exists():
        raise SystemExit(f"database not found: {path}")
    connection = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row
    return connection


def scalar(connection: sqlite3.Connection, sql: str, params: tuple = ()) -> int:
    row = connection.execute(sql, params).fetchone()
    return int(row[0]) if row and row[0] is not None else 0


def build(connection: sqlite3.Connection, path: Path) -> tuple[list[str], bool]:
    runs = scalar(connection, "SELECT COUNT(*) FROM strategy_backtest_runs")
    metrics = scalar(connection, "SELECT COUNT(*) FROM strategy_backtest_metrics")
    trades = scalar(connection, "SELECT COUNT(*) FROM strategy_backtest_trades")
    equity = scalar(connection, "SELECT COUNT(*) FROM strategy_backtest_equity")

    missing_metrics = scalar(
        connection,
        "SELECT COUNT(*) FROM strategy_backtest_runs AS r "
        "LEFT JOIN strategy_backtest_metrics AS m ON m.run_id = r.run_id "
        "WHERE m.run_id IS NULL",
    )
    orphan_metrics = scalar(
        connection,
        "SELECT COUNT(*) FROM strategy_backtest_metrics AS m "
        "LEFT JOIN strategy_backtest_runs AS r ON r.run_id = m.run_id "
        "WHERE r.run_id IS NULL",
    )
    orphan_trades = scalar(
        connection,
        "SELECT COUNT(*) FROM strategy_backtest_trades AS t "
        "LEFT JOIN strategy_backtest_runs AS r ON r.run_id = t.run_id "
        "WHERE r.run_id IS NULL",
    )
    orphan_equity = scalar(
        connection,
        "SELECT COUNT(*) FROM strategy_backtest_equity AS e "
        "LEFT JOIN strategy_backtest_runs AS r ON r.run_id = e.run_id "
        "WHERE r.run_id IS NULL",
    )

    session_mismatch = connection.execute(
        """
        SELECT r.run_id, m.sessions, COUNT(e.run_id) AS points
        FROM strategy_backtest_runs AS r
        JOIN strategy_backtest_metrics AS m ON m.run_id = r.run_id
        LEFT JOIN strategy_backtest_equity AS e ON e.run_id = r.run_id
        GROUP BY r.run_id
        HAVING m.sessions != points
        """
    ).fetchall()
    trade_mismatch = connection.execute(
        """
        SELECT r.run_id, m.trades, COUNT(t.run_id) AS stored
        FROM strategy_backtest_runs AS r
        JOIN strategy_backtest_metrics AS m ON m.run_id = r.run_id
        LEFT JOIN strategy_backtest_trades AS t ON t.run_id = r.run_id
        GROUP BY r.run_id
        HAVING m.trades != stored
        """
    ).fetchall()
    duplicates = connection.execute(
        """
        SELECT data_fingerprint, spec_json, COUNT(*) AS total
        FROM strategy_backtest_runs
        GROUP BY data_fingerprint, spec_json
        HAVING total > 1
        """
    ).fetchall()
    sizes = connection.execute(
        """
        SELECT 'runs' AS name, COUNT(*) AS rows FROM strategy_backtest_runs
        UNION ALL SELECT 'metrics', COUNT(*) FROM strategy_backtest_metrics
        UNION ALL SELECT 'trades', COUNT(*) FROM strategy_backtest_trades
        UNION ALL SELECT 'equity', COUNT(*) FROM strategy_backtest_equity
        """
    ).fetchall()

    checks = [
        ("Every run has a metrics row", missing_metrics == 0, missing_metrics),
        ("Metrics never orphan", orphan_metrics == 0, orphan_metrics),
        ("Trades never orphan", orphan_trades == 0, orphan_trades),
        ("Equity rows never orphan", orphan_equity == 0, orphan_equity),
        ("Equity points match `sessions`", not session_mismatch, len(session_mismatch)),
        ("Trade rows match `trades`", not trade_mismatch, len(trade_mismatch)),
        ("No duplicate identity (fingerprint + spec)", not duplicates, len(duplicates)),
    ]
    ok = all(item[1] for item in checks)

    lines = [
        "# Stage E — backtest retention audit (E-4)",
        "",
        "Generated by `scripts/audit_backtest_retention.py`, opened read-only.",
        "**No retention period is chosen and nothing is deleted here**; a policy",
        "needs the lead's approval.",
        "",
        f"- Database: `{path}`",
        f"- Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        "",
        "## Row counts",
        "",
        "| Table | Rows |",
        "| --- | --- |",
    ]
    for row in sizes:
        lines.append(f"| `strategy_backtest_{row['name']}` | {row['rows']} |")
    lines += [
        "",
        f"- Runs: {runs}, metrics: {metrics}, trades: {trades}, equity points: {equity}",
        "",
        "## Integrity checks",
        "",
        "| Check | Expected | Actual | Result |",
        "| --- | --- | --- | --- |",
    ]
    for name, passed, actual in checks:
        lines.append(f"| {name} | 0 violations | {actual} | {'PASS' if passed else 'FAIL'} |")

    lines += [
        "",
        "## Retention behaviour",
        "",
        "- A run is written once, inside one transaction with its metrics, trades",
        "  and equity curve; the repository rejects a duplicate `run_id` with",
        "  `DuplicateRunError` instead of overwriting.",
        "- Re-submitting an identical specification + data fingerprint returns the",
        "  stored run (`created=False`) and adds no rows; `force=True` stores a",
        "  suffixed run id rather than replacing the original.",
        "- `price_revisions` and `fx_revisions` are append-only ledgers; nothing in",
        "  the backtesting path updates or deletes them.",
        "- There is no automatic pruning, vacuum or TTL. Growth is proportional to",
        "  the number of distinct specifications × distinct data fingerprints.",
        "",
        "## Decision",
        "",
        "No retention action is taken in V2.3.2. If a policy is wanted later, the",
        "candidate is: keep every run referenced by a report or an external note,",
        "and prune only runs whose report was never rendered and whose fingerprint",
        "is superseded by a newer accepted run — to be decided by the lead.",
        "",
    ]
    return lines, ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--report", type=Path, default=REPORT)
    args = parser.parse_args()
    connection = connect(args.db)
    try:
        lines, ok = build(connection, args.db)
    finally:
        connection.close()
    text = "\n".join(lines)
    print(text)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(text, encoding="utf-8", newline="\r\n")
    print(f"written: {args.report}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
