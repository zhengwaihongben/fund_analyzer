"""Stage E, batch E-2b: short-window real-data smoke test on the working database.

The run proves that the price/FX PIT layer, the engine, the cost model, the
metrics and the persistence layer work together on real data.  It is *not* a
performance claim: the working database only holds a short PIT window.

Run with::

    python scripts/smoke_backtest_real.py [--db PATH] [--capital 100000]

The report is written to ``docs/development/stageE_real_smoke.md``.
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from datetime import date, datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fa.backtesting import (  # noqa: E402
    CostModel,
    DataAccess,
    Instrument,
    RebalanceRule,
    StrategySpec,
    Weighting,
    run_backtest,
)
from fa.backtesting.runner import decision_instant  # noqa: E402
from fa.data.database.repository import Repository  # noqa: E402
from fa.utils.calendars import calendar_for  # noqa: E402

DEFAULT_DB = ROOT / "data" / "database" / "fund_analyzer.db"
REPORT = ROOT / "docs" / "development" / "stageE_real_smoke.md"


def pit_dates(repository: Repository, ticker: str) -> list[date]:
    series = repository.load_prices(ticker)
    if series is None:
        return []
    return [point.price_date for point in series.points if point.available_at is not None]


def choose_pair(repository: Repository) -> tuple[list[Instrument], list[date]]:
    """Pick two real instruments whose PIT windows overlap, plus that window."""
    best: tuple[list[Instrument], list[date]] | None = None
    metadata: dict[str, tuple[str, str]] = {}
    for ticker in ("LLY", "JNJ", "AZN", "NOVN", "ROP SW", "MRK", "ABBV", "UNH", "TMO", "AMGN"):
        found = repository.price_metadata(ticker)
        if found is not None:
            metadata[ticker] = found
    for ticker, (market, currency) in metadata.items():
        if currency == "CNY":
            continue
        try:
            calendar_for(market)
        except Exception:  # noqa: BLE001 - unsupported venue, skip the ticker
            continue
    for first in sorted(metadata):
        for second in sorted(metadata):
            if first >= second:
                continue
            days_first = set(pit_dates(repository, first))
            days_second = set(pit_dates(repository, second))
            common = sorted(days_first & days_second)
            if len(common) < 5:
                continue
            # Keep the window's FX available: both foreign currencies must be
            # published over the same span, and the execution instant must be
            # able to see the rate (otherwise every order is skipped).
            usable = []
            access = DataAccess(repository)
            for day in common:
                instant = datetime.combine(day, datetime.max.time(), tzinfo=timezone.utc)
                try:
                    access.price_at(Instrument(first, *metadata[first]), instant, day)
                    access.price_at(Instrument(second, *metadata[second]), instant, day)
                    for ticker in (first, second):
                        currency = metadata[ticker][1]
                        entry = access.fx_rate(currency, instant, day)
                        if entry is None:
                            raise LookupError(f"{currency} 在 {day} 沒有可用匯率")
                except Exception:  # noqa: BLE001 - missing PIT data on that day
                    continue
                usable.append(day)
            if len(usable) < 5:
                continue
            usable = usable[-10:]
            candidate = (
                [Instrument(first, *metadata[first]), Instrument(second, *metadata[second])],
                usable,
            )
            if best is None or len(candidate[1]) > len(best[1]):
                best = candidate
    if best is None:
        raise SystemExit("no pair of instruments with a usable PIT window was found")
    return best


def _pct(value: float | None) -> str:
    return "—" if value is None else f"{value:.6%}"


def build_report(
    *,
    db: Path,
    version: int,
    instruments: list[Instrument],
    window: list[date],
    spec: StrategySpec,
    run,
    created: bool,
    reloaded,
    checks: list[tuple[str, str, str, bool]],
) -> str:
    lines = [
        "# Stage E — real-data short-window smoke test (E-2b)",
        "",
        "Generated by `scripts/smoke_backtest_real.py`. This is a pipeline and PIT",
        "verification on the working database, **not** evidence of strategy performance.",
        "",
        f"- Database: `{db}`",
        f"- Schema version: {version}",
        f"- Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- Instruments: {', '.join(f'{i.ticker} ({i.market}/{i.currency})' for i in instruments)}",
        f"- Window: {window[0]} … {window[-1]} ({len(window)} sessions with PIT prices)",
        f"- Strategy: `{spec.spec_id}`, weighting `{spec.weighting.value}`, "
        f"rebalance `{spec.rebalance.frequency.value}` anchor {spec.rebalance.anchor}, "
        f"initial capital {spec.initial_capital:.2f} CNY",
        f"- Run id: `{run.run_id}`",
        f"- Created by this call: {created}",
        "",
        "## Result summary",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Sessions | {run.metrics.sessions} |",
        f"| Trades | {run.metrics.trades} |",
        f"| Final equity | {run.equity_curve[-1].total_base:.2f} CNY |",
        f"| Final cash | {run.equity_curve[-1].cash_base:.2f} CNY |",
        f"| CAGR | {_pct(run.metrics.cagr)} |",
        f"| Annualised vol | {_pct(run.metrics.annualised_vol)} |",
        f"| Sharpe | {run.metrics.sharpe} |",
        f"| Sortino | {run.metrics.sortino} |",
        f"| Max drawdown | {_pct(run.metrics.max_drawdown)} |",
        f"| Exposure | {_pct(run.metrics.exposure)} |",
        f"| Total costs | {run.metrics.total_costs_base:.2f} CNY |",
        f"| Data fingerprint | `{run.data_fingerprint}` |",
        "",
        "## Point-in-time and persistence checks",
        "",
        "| Check | Expected | Actual | Result |",
        "| --- | --- | --- | --- |",
    ]
    for name, expected, actual, ok in checks:
        lines.append(f"| {name} | {expected} | {actual} | {'PASS' if ok else 'FAIL'} |")
    lines += [
        "",
        "## Trade detail (PIT execution prices)",
        "",
        "| Session | Ticker | Side | Quantity | Price (local) | FX | FX source | Costs |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for trade in run.trades:
        lines.append(
            f"| {trade.session} | `{trade.ticker}` | {trade.side} | {trade.quantity:.6f} | "
            f"{trade.price_local:.4f} | {trade.fx_rate:.6f} | {trade.fx_source} | "
            f"{(trade.commission_base + trade.slippage_base + trade.fx_spread_base):.2f} |"
        )
    lines += [
        "",
        "## Anomalies recorded by the run",
        "",
    ]
    if run.anomalies:
        for item in run.anomalies:
            lines.append(f"- {item}")
    else:
        lines.append("- None.")
    lines += [
        "",
        "## Persistence round trip",
        "",
        f"- `load_backtest_run('{run.run_id}')` returned {len(reloaded.trades)} trades and "
        f"{len(reloaded.equity_curve)} equity points.",
        f"- Reloaded final equity: {reloaded.equity_curve[-1].total_base:.2f} CNY.",
        f"- Metrics match: {reloaded.metrics.as_dict() == run.metrics.as_dict()}.",
        "",
        "## Known limits",
        "",
        "- The database only holds a short PIT window, so this run is a smoke test;",
        "  multi-year performance claims require the documented two-year ingest.",
        "- Legacy rows without publication metadata stay invisible to `prices_as_of()`",
        "  and are never used here (decision Q1).",
        "- A repeat submission of this exact specification returns the stored run",
        "  (`created=False`); that is the idempotency evidence for BT-04, not a",
        "  failure of the smoke test.",
        "- Benchmark curve is not configured in this smoke run; it is covered by the",
        "  synthetic acceptance and the benchmark unit tests.",
        "",
    ]
    return "\n".join(lines)


def schema_version(path: Path) -> int | None:
    with sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True) as probe:
        row = probe.execute("SELECT MAX(version) FROM schema_version").fetchone()
    return int(row[0]) if row and row[0] is not None else None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--capital", type=float, default=100_000.0)
    parser.add_argument("--report", type=Path, default=REPORT)
    args = parser.parse_args()
    repository = Repository(args.db)
    try:
        version = schema_version(args.db)
        if version != 4:
            raise SystemExit(f"schema version {version} != 4; run the migrations first")
        instruments, window = choose_pair(repository)
        spec = StrategySpec(
            spec_id=f"stagee-real-smoke-{window[0]:%Y%m%d}-{window[-1]:%Y%m%d}",
            universe=instruments,
            weighting=Weighting("equal"),
            start=window[0],
            end=window[-1],
            initial_capital=args.capital,
            rebalance=RebalanceRule(frequency="monthly", anchor=window[0].day),
            drift_threshold=0.0,
            costs=CostModel(),
        )
        run, created = run_backtest(spec, repository, now=datetime.now(timezone.utc))
        access = DataAccess(repository)
        checks: list[tuple[str, str, str, bool]] = []
        # Every trade price must equal the PIT price the engine was allowed to see
        # at that session's execution instant.
        mismatch = 0
        for trade in run.trades:
            instrument = next(item for item in instruments if item.ticker == trade.ticker)
            # Same instant the engine uses: the execution session's close for the
            # venues trading that day, plus the documented 30-minute lag.
            instant = decision_instant(spec, trade.session, lag_minutes=30)
            try:
                point = access.price_at(instrument, instant, trade.session)
            except Exception:  # noqa: BLE001 - missing data would be a PIT failure here
                mismatch += 1
                continue
            if abs(point.close - trade.price_local) > 1e-9:
                mismatch += 1
        checks.append(
            ("At least one trade was executed", "> 0", str(len(run.trades)), len(run.trades) > 0)
        )
        checks.append(
            ("Trade prices match the PIT close", "0 mismatches", f"{mismatch} mismatches", mismatch == 0)
        )
        checks.append(
            ("Cash never negative", ">= 0", f"{min(p.cash_base for p in run.equity_curve):.6f}",
             min(p.cash_base for p in run.equity_curve) >= -1e-9)
        )
        checks.append(
            ("Equity identity", "cash + holdings",
             f"{run.equity_curve[-1].total_base:.2f}",
                 abs(
                     run.equity_curve[-1].total_base
                     - run.equity_curve[-1].cash_base
                     - run.equity_curve[-1].holdings_base
                 ) <= 1e-6,
             )
        )
        reloaded = repository.load_backtest_run(run.run_id)
        checks.append(
            ("Persistence round trip", "same trades", f"{len(reloaded.trades)}",
             len(reloaded.trades) == len(run.trades))
        )
        checks.append(
            ("Metrics reproduced after reload", "equal dict",
             str(reloaded.metrics.as_dict() == run.metrics.as_dict()),
             reloaded.metrics.as_dict() == run.metrics.as_dict())
        )
        checks.append(
            ("Duplicate request is idempotent", "created=False",
             str(run_backtest(spec, repository, now=datetime.now(timezone.utc))[1]),
             run_backtest(spec, repository, now=datetime.now(timezone.utc))[1] is False)
        )
        text = build_report(
            db=args.db, version=version, instruments=instruments, window=window,
            spec=spec, run=run, created=created, reloaded=reloaded, checks=checks,
        )
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(text, encoding="utf-8", newline="\r\n")
        failed = [name for name, _expected, _actual, ok in checks if not ok]
        print(f"run_id={run.run_id} created={created} trades={len(run.trades)} "
              f"sessions={len(run.equity_curve)} failed_checks={len(failed)}")
        print(f"report={args.report.relative_to(ROOT)}")
        for name, expected, actual, ok in checks:
            if not ok:
                print(f"FAIL {name}: expected={expected} actual={actual}")
        return 1 if failed else 0
    finally:
        repository.close()


if __name__ == "__main__":
    raise SystemExit(main())
